fruits=["apple","banana","mango"]
print(fruits[0])  # apple
print(fruits[1])  # banana
print(fruits[2])  # mango

fruits[1]="orange" #change the value of fruits[1]
print("after changing value of fruits[1]:",fruits[1])

fruits.append("grape")
fruits.remove("apple")

print(len(fruits))

